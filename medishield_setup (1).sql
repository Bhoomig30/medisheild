-- PART 3: HELPER VIEWS (new in Phase 1)
CREATE VIEW V_SupplierChain AS
SELECT s.supplier_id, s.name, s.tier, s.material, s.region, s.country,
 s.parent_id, p.name AS parent_name
FROM Suppliers s LEFT JOIN Suppliers p ON s.parent_id = p.supplier_id;

CREATE VIEW V_Tier1Root AS
SELECT s.supplier_id, s.name, s.tier, s.material, s.region,
 CASE s.tier WHEN 1 THEN s.supplier_id WHEN 2 THEN s.parent_id ELSE p.parent_id END AS tier1_id
FROM Suppliers s LEFT JOIN Suppliers p ON s.parent_id = p.supplier_id;

CREATE VIEW V_StockDays AS
SELECT material, unit, stock_units, daily_usage, lead_time_days,
 stock_units / daily_usage AS days_of_stock
FROM Stock;
