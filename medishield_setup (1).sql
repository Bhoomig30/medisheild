-- PART 1: TABLES
CREATE COLUMN TABLE Suppliers (
 supplier_id NVARCHAR(10) PRIMARY KEY, name NVARCHAR(100), tier INTEGER,
 parent_id NVARCHAR(10), material NVARCHAR(60), region NVARCHAR(60),
 country NVARCHAR(40), simulated BOOLEAN DEFAULT TRUE);

CREATE COLUMN TABLE Stock (
 material NVARCHAR(60) PRIMARY KEY, unit NVARCHAR(10),
 stock_units INTEGER, daily_usage INTEGER, lead_time_days INTEGER);

CREATE COLUMN TABLE SupplierDeclarations (
 declaration_id NVARCHAR(10) PRIMARY KEY, tier1_supplier NVARCHAR(10),
 material NVARCHAR(60), upstream_name NVARCHAR(100), upstream_region NVARCHAR(60),
 share_percent INTEGER, backup_available BOOLEAN, lead_time_days INTEGER,
 status NVARCHAR(15), submitted_at TIMESTAMP);

CREATE COLUMN TABLE Risks (
 risk_id NVARCHAR(10) PRIMARY KEY, event NVARCHAR(300), region NVARCHAR(60),
 affected_supplier NVARCHAR(10), tier INTEGER, confidence NVARCHAR(10),
 source NVARCHAR(200), reason NVARCHAR(300), evidence_type NVARCHAR(15),
 matched_on NVARCHAR(100));

CREATE COLUMN TABLE Impacts (
 risk_id NVARCHAR(10) PRIMARY KEY, delay_days INTEGER,
 days_of_stock INTEGER, production_at_risk NVARCHAR(100));

CREATE COLUMN TABLE Options (
 option_id NVARCHAR(10) PRIMARY KEY, risk_id NVARCHAR(10), type NVARCHAR(30),
 cost_estimate DECIMAL(12,2), delay_saved_days INTEGER, option_rank INTEGER);

CREATE COLUMN TABLE Messages (
 message_id NVARCHAR(10) PRIMARY KEY, risk_id NVARCHAR(10), to_supplier NVARCHAR(10),
 body NVARCHAR(2000), language NVARCHAR(5), body_translated NVARCHAR(2000),
 status NVARCHAR(20), reply_text NVARCHAR(1000), reply_timestamp TIMESTAMP);

CREATE COLUMN TABLE ApprovalRule (
 rule_id NVARCHAR(10) PRIMARY KEY, threshold_cost DECIMAL(12,2), approver_role NVARCHAR(30));

CREATE COLUMN TABLE Simulation (
 sim_id NVARCHAR(10) PRIMARY KEY, scenario_type NVARCHAR(30), duration_days INTEGER,
 region NVARCHAR(60), impact NVARCHAR(500), options NVARCHAR(1000));

CREATE COLUMN TABLE AuditLog (
 audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 risk_id NVARCHAR(10), option_id NVARCHAR(10), action NVARCHAR(30),
 approver_role NVARCHAR(30), approved_by NVARCHAR(50), reason NVARCHAR(300),
 status NVARCHAR(20), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);

